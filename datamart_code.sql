GO

/* ---------------------------------------------------------------------
   FactFinance
   --------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.FactFinance', N'U') IS NULL
CREATE TABLE dbo.FactFinance (
    FinanceKey         int IDENTITY(1,1) NOT NULL,
    DateKey            int      NOT NULL,
    OrganizationKey    int      NOT NULL,
    DepartmentGroupKey int      NOT NULL,
    ScenarioKey        int      NOT NULL,
    AccountKey         int      NOT NULL,
    Amount             float    NOT NULL,
    [Date]             datetime NULL,
    CONSTRAINT PK_FactFinance PRIMARY KEY CLUSTERED (FinanceKey),          -- [ADDED]
    CONSTRAINT FK_FactFinance_DimAccount
        FOREIGN KEY (AccountKey)         REFERENCES dbo.DimAccount (AccountKey),
    CONSTRAINT FK_FactFinance_DimDate
        FOREIGN KEY (DateKey)            REFERENCES dbo.DimDate (DateKey),
    CONSTRAINT FK_FactFinance_DimDepartmentGroup
        FOREIGN KEY (DepartmentGroupKey) REFERENCES dbo.DimDepartmentGroup (DepartmentGroupKey),
    CONSTRAINT FK_FactFinance_DimOrganization
        FOREIGN KEY (OrganizationKey)    REFERENCES dbo.DimOrganization (OrganizationKey),
    CONSTRAINT FK_FactFinance_DimScenario
        FOREIGN KEY (ScenarioKey)        REFERENCES dbo.DimScenario (ScenarioKey)
);
GO

/* ---------------------------------------------------------------------
   ETL_Log  [ADDED] - one row per package run, filled by SSIS.
   Used in the demo to show what each load (full / delta) did.
   --------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.ETL_Log', N'U') IS NULL
CREATE TABLE dbo.ETL_Log (
    LogID          int IDENTITY(1,1) NOT NULL,
    PackageName    nvarchar(100) NOT NULL,
    StartTime      datetime      NOT NULL,
    EndTime        datetime      NULL,
    RowsRead       int           NULL,
    RowsInserted   int           NULL,
    RowsUpdated    int           NULL,   -- Type 1 changes
    RowsHistorized int           NULL,   -- Type 2 changes (new versions)
    RowsRejected   int           NULL,
    [Status]       nvarchar(20)  NULL,   -- 'Success' / 'Failure'
    CONSTRAINT PK_ETL_Log PRIMARY KEY CLUSTERED (LogID)
);
GO

/* ---------------------------------------------------------------------
   Check: should list 8 tables, all with 0 rows for now
   --------------------------------------------------------------------- */
SELECT t.name AS TableName,
       (SELECT COUNT(*) FROM sys.columns c WHERE c.object_id = t.object_id) AS NbColumns,
       SUM(p.rows) AS NbRows
FROM sys.tables t
JOIN sys.partitions p ON p.object_id = t.object_id AND p.index_id IN (0, 1)
GROUP BY t.name, t.object_id
ORDER BY t.name;
GO