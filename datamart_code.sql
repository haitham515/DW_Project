   --------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.DimCurrency', N'U') IS NULL
CREATE TABLE dbo.DimCurrency (
    CurrencyKey          int IDENTITY(1,1) NOT NULL,
    CurrencyAlternateKey nchar(3)     NOT NULL,
    CurrencyName         nvarchar(50) NOT NULL,
    CONSTRAINT PK_DimCurrency_CurrencyKey PRIMARY KEY CLUSTERED (CurrencyKey),
    CONSTRAINT AK_DimCurrency_CurrencyAlternateKey UNIQUE NONCLUSTERED (CurrencyAlternateKey)
);
GO

/* ---------------------------------------------------------------------
   DimOrganization  -- SCD dimension (Type 2 + Type 1)
     Type 2 (history) : PercentageOfOwnership, CurrencyKey
     Type 1 (update)  : OrganizationName
   --------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.DimOrganization', N'U') IS NULL
CREATE TABLE dbo.DimOrganization (
    OrganizationKey                int IDENTITY(1,1) NOT NULL,  -- surrogate key (one per version)
    OrganizationAlternateKey       int          NOT NULL,       -- [ADDED] business key = source OrganizationKey, never changes
    ParentOrganizationKey          int          NULL,
    ParentOrganizationAlternateKey int          NULL,           -- [ADDED] source parent key, used to rebuild the hierarchy
    PercentageOfOwnership          decimal(5,4) NULL,           -- [CHANGED] nvarchar(16) in the statement; numeric so it can be
                                                                --           compared reliably by the SCD and used in calculations
    OrganizationName               nvarchar(50) NULL,
    CurrencyKey                    int          NULL,
    StartDate                      datetime     NOT NULL,       -- [ADDED] version valid from
    EndDate                        datetime     NULL,           -- [ADDED] version valid until (NULL = current version)
    IsCurrent AS (CASE WHEN EndDate IS NULL THEN CAST(1 AS bit)
                       ELSE CAST(0 AS bit) END),                -- [ADDED] computed from EndDate, always consistent
    CONSTRAINT PK_DimOrganization PRIMARY KEY CLUSTERED (OrganizationKey),
    CONSTRAINT FK_DimOrganization_DimCurrency
        FOREIGN KEY (CurrencyKey) REFERENCES dbo.DimCurrency (CurrencyKey),
    CONSTRAINT FK_DimOrganization_DimOrganization
        FOREIGN KEY (ParentOrganizationKey) REFERENCES dbo.DimOrganization (OrganizationKey)
);
GO

-- [ADDED] Guarantees at most ONE current version per organization
IF NOT EXISTS (SELECT 1 FROM sys.indexes
               WHERE name = N'UX_DimOrganization_CurrentVersion'
                 AND object_id = OBJECT_ID(N'dbo.DimOrganization'))
CREATE UNIQUE NONCLUSTERED INDEX UX_DimOrganization_CurrentVersion
    ON dbo.DimOrganization (OrganizationAlternateKey)
    WHERE EndDate IS NULL;
GO

