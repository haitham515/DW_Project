/* =====================================================================
   LightFinanceDW - Creation of the Finance datamart
   ---------------------------------------------------------------------
   Based on the "code support" given in the project statement, with:
     - the PDF copy/paste errors fixed ([float], ALTER TABLE)
     - foreign keys declared inside each CREATE TABLE (same names as
       the statement, same effect)
     - additions needed by the project (marked  -- [ADDED])
   The script can be run several times: it only creates what is missing.
   Run it in SSMS, connected to the Database Engine (localhost).
   ===================================================================== */

USE master;
GO

-- Same collation as the sources (AdventureWorks2025 / AdventureWorksDW2025).
-- Without it, the database takes the server collation (French_CI_AS here)
-- and every query that compares text between the sources and the datamart
-- fails with "conflit de classement" (Msg 468).
IF DB_ID(N'LightFinanceDW') IS NULL
    CREATE DATABASE LightFinanceDW COLLATE SQL_Latin1_General_CP1_CI_AS;
GO

USE LightFinanceDW;
GO

/* ---------------------------------------------------------------------
   DimAccount  (parent-child hierarchy, business key = AccountCodeAlternateKey)
   --------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.DimAccount', N'U') IS NULL
CREATE TABLE dbo.DimAccount (
    AccountKey                    int IDENTITY(1,1) NOT NULL,
    ParentAccountKey              int           NULL,
    AccountCodeAlternateKey       int           NULL,
    ParentAccountCodeAlternateKey int           NULL,
    AccountDescription            nvarchar(50)  NULL,
    AccountType                   nvarchar(50)  NULL,
    Operator                      nvarchar(50)  NULL,
    CustomMembers                 nvarchar(300) NULL,
    ValueType                     nvarchar(50)  NULL,
    CustomMemberOptions           nvarchar(200) NULL,
    CONSTRAINT PK_DimAccount PRIMARY KEY CLUSTERED (AccountKey),
    CONSTRAINT FK_DimAccount_DimAccount
        FOREIGN KEY (ParentAccountKey) REFERENCES dbo.DimAccount (AccountKey)
);
GO

